type IconProps = Omit<SVGProps<SVGSVGElement>, 'children'> & {
  size?: number;
};

/**
 * Icons for the app's own controls, drawn like @levuche/ui's icons: a 24 px
 * box, 2 px stroke, in the text colour. They're always beside words or
 * inside a control with its own name, so screen readers skip them.
 */
function Svg({
  size = 18,
  children,
  ...props
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      focusable={false}
      {...props}
    >
      {children}
    </svg>
  );
}

